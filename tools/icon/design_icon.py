"""
Re-MicroG RE launcher icon: Android head with push "signal" waves on a deep teal gradient.
One geometry drives both the adaptive-icon vector drawables and the legacy bitmaps,
so every density and every launcher shape shows the same design.

Usage: python3 -I design_icon.py <res dir> <preview.png>
"""
import math
import sys

import numpy as np
from PIL import Image, ImageDraw

RES, PREVIEW = sys.argv[1], sys.argv[2]

# ---- Design (108 x 108 adaptive canvas, safe zone = circle r 33 around the center) ----
DY = 4  # vertical nudge for optical centering
GREEN = "#3DDC84"           # Android brand green
NAVY = "#073042"            # Android navy, used for the eyes
BG_START, BG_END = "#0E4D5C", "#04212B"
GLOW = (61, 220, 132)       # soft green glow behind the head
HEAD_C, HEAD_R = (54.0, 66.0 + DY), 21.0
EYES = [(45.0, 56.5 + DY), (63.0, 56.5 + DY)]
EYE_R = 2.4
ANTENNAE = [((42.5, 49.5 + DY), (36.5, 40.5 + DY)), ((65.5, 49.5 + DY), (71.5, 40.5 + DY))]
ANTENNA_W = 3.0
WAVE_CENTER = ANTENNAE[1][1]
WAVES = [(6.5, 1.0), (11.5, 0.55)]   # (radius, opacity)
WAVE_W = 2.4
WAVE_FROM, WAVE_TO = -72.0, -18.0  # degrees, y axis pointing down


def wave_points(r):
    cx, cy = WAVE_CENTER
    a0, a1 = math.radians(WAVE_FROM), math.radians(WAVE_TO)
    return (cx + r * math.cos(a0), cy + r * math.sin(a0)), (cx + r * math.cos(a1), cy + r * math.sin(a1))


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def circle_path(cx, cy, r):
    return f"M{f(cx - r)},{f(cy)}a{f(r)},{f(r)} 0 1,0 {f(2 * r)},0a{f(r)},{f(r)} 0 1,0 {f(-2 * r)},0z"


def head_path(dx=0.0, dy=0.0):
    (cx, cy), r = HEAD_C, HEAD_R
    return f"M{f(cx - r + dx)},{f(cy + dy)}A{f(r)},{f(r)} 0 0,1 {f(cx + r + dx)},{f(cy + dy)}Z"


def safe_zone_check():
    pts = [(HEAD_C[0] - HEAD_R, HEAD_C[1]), (HEAD_C[0] + HEAD_R, HEAD_C[1]), (HEAD_C[0], HEAD_C[1] - HEAD_R)]
    pts += [a[1] for a in ANTENNAE]
    for r, _ in WAVES:
        pts += list(wave_points(r))
    worst = max(math.hypot(x - 54, y - 54) for x, y in pts)
    assert worst <= 31.5, worst
    return worst


# ---- Vector drawables ----
XML_HEAD = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Re-MicroG RE launcher icon, generated by design_icon.py -->\n'


def foreground_xml(mono=False):
    head = "#FFFFFFFF" if mono else GREEN
    wave = "#FFFFFFFF"
    parts = []
    if not mono:
        # flat drop shadow, offset down
        parts.append(f'    <path android:fillColor="#33000000" android:pathData="{head_path(0, 1.6)}" />')
    for (x0, y0), (x1, y1) in ANTENNAE:
        parts.append(f'    <path android:strokeColor="{head}" android:strokeWidth="{f(ANTENNA_W)}" '
                     f'android:strokeLineCap="round" android:pathData="M{f(x0)},{f(y0)}L{f(x1)},{f(y1)}" />')
    parts.append(f'    <path android:fillColor="{head}" android:pathData="{head_path()}" />')
    eyes = " ".join(circle_path(x, y, EYE_R) for x, y in EYES)
    if mono:
        # monochrome icons are a single tint: punch the eyes out instead of painting them
        parts[-1] = (f'    <path android:fillColor="{head}" android:fillType="evenOdd" '
                     f'android:pathData="{head_path()} {eyes}" />')
    else:
        parts.append(f'    <path android:fillColor="{NAVY}" android:pathData="{eyes}" />')
    for r, alpha in WAVES:
        (sx, sy), (ex, ey) = wave_points(r)
        parts.append(f'    <path android:strokeColor="{wave}" android:strokeAlpha="{f(alpha)}" '
                     f'android:strokeWidth="{f(WAVE_W)}" android:strokeLineCap="round" '
                     f'android:pathData="M{f(sx)},{f(sy)}A{f(r)},{f(r)} 0 0,1 {f(ex)},{f(ey)}" />')
    body = "\n".join(parts)
    return (XML_HEAD + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n' + body + "\n</vector>\n")


def background_xml():
    g = GLOW
    return (XML_HEAD + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            '    <path android:pathData="M0,0h108v108h-108z">\n'
            '        <aapt:attr name="android:fillColor">\n'
            '            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108">\n'
            f'                <item android:offset="0" android:color="#FF{BG_START[1:]}" />\n'
            f'                <item android:offset="1" android:color="#FF{BG_END[1:]}" />\n'
            '            </gradient>\n'
            '        </aapt:attr>\n'
            '    </path>\n'
            '    <path android:pathData="M0,0h108v108h-108z">\n'
            '        <aapt:attr name="android:fillColor">\n'
            f'            <gradient android:type="radial" android:centerX="54" android:centerY="{f(54 + DY)}" android:gradientRadius="42">\n'
            f'                <item android:offset="0" android:color="#40{g[0]:02X}{g[1]:02X}{g[2]:02X}" />\n'
            f'                <item android:offset="1" android:color="#00{g[0]:02X}{g[1]:02X}{g[2]:02X}" />\n'
            '            </gradient>\n'
            '        </aapt:attr>\n'
            '    </path>\n'
            '</vector>\n')


# ---- Bitmap rendering (legacy icons + preview), 4x supersampled ----
def hex_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def render(size):
    ss = size * 4
    k = ss / 108.0
    yy, xx = np.mgrid[0:ss, 0:ss].astype(np.float32) / k
    t = np.clip((xx + yy) / 216.0, 0, 1)[..., None]
    a, b = np.array(hex_rgb(BG_START), np.float32), np.array(hex_rgb(BG_END), np.float32)
    rgb = a * (1 - t) + b * t
    d = np.hypot(xx - 54, yy - (54 + DY)) / 42.0
    glow = (np.clip(1 - d, 0, 1) * (0x40 / 255.0))[..., None]
    rgb = rgb * (1 - glow) + np.array(GLOW, np.float32) * glow
    img = Image.fromarray(rgb.astype(np.uint8), "RGB").convert("RGBA")

    def layer():
        return Image.new("RGBA", (ss, ss), (0, 0, 0, 0))

    def P(x, y):
        return (x * k, y * k)

    (cx, cy), r = HEAD_C, HEAD_R
    head_box = [P(cx - r, cy - r), P(cx + r, cy + r)]

    shadow = layer()
    ImageDraw.Draw(shadow).pieslice([P(cx - r, cy - r + 1.6), P(cx + r, cy + r + 1.6)], 180, 360, fill=(0, 0, 0, 0x33))
    img = Image.alpha_composite(img, shadow)

    fg = layer()
    dr = ImageDraw.Draw(fg)
    green = hex_rgb(GREEN) + (255,)
    for (x0, y0), (x1, y1) in ANTENNAE:
        dr.line([P(x0, y0), P(x1, y1)], fill=green, width=round(ANTENNA_W * k))
        for x, y in ((x0, y0), (x1, y1)):
            rr = ANTENNA_W / 2
            dr.ellipse([P(x - rr, y - rr), P(x + rr, y + rr)], fill=green)
    dr.pieslice(head_box, 180, 360, fill=green)
    for x, y in EYES:
        dr.ellipse([P(x - EYE_R, y - EYE_R), P(x + EYE_R, y + EYE_R)], fill=hex_rgb(NAVY) + (255,))
    img = Image.alpha_composite(img, fg)

    for rad, alpha in WAVES:
        wl = layer()
        wd = ImageDraw.Draw(wl)
        col = (255, 255, 255, round(255 * alpha))
        wx, wy = WAVE_CENTER
        hw = WAVE_W / 2
        wd.arc([P(wx - rad - hw, wy - rad - hw), P(wx + rad + hw, wy + rad + hw)], WAVE_FROM, WAVE_TO, fill=col, width=round(WAVE_W * k))
        for x, y in wave_points(rad):
            rr = WAVE_W / 2
            wd.ellipse([P(x - rr, y - rr), P(x + rr, y + rr)], fill=col)
        img = Image.alpha_composite(img, wl)
    return img.resize((size, size), Image.LANCZOS)


def masked(img, shape):
    s = img.size[0]
    big = s * 4
    m = Image.new("L", (big, big), 0)
    if shape == "circle":
        ImageDraw.Draw(m).ellipse((0, 0, big - 1, big - 1), fill=255)
    else:
        ImageDraw.Draw(m).rounded_rectangle((0, 0, big - 1, big - 1), radius=int(big * 0.22), fill=255)
    out = img.copy()
    out.putalpha(m.resize((s, s), Image.LANCZOS))
    return out


def legacy(size):
    # Legacy icons show the visible 72dp of the 108dp canvas, like a launcher would
    full = render(round(size * 108 / 72))
    off = (full.size[0] - size) // 2
    return full.crop((off, off, off + size, off + size))


if __name__ == "__main__":
    print("max distance from center:", round(safe_zone_check(), 2), "(safe zone 33)")
    draw = f"{RES}/drawable"
    open(f"{draw}/ic_launcher_re_background.xml", "w").write(background_xml())
    open(f"{draw}/ic_launcher_re_foreground.xml", "w").write(foreground_xml())
    open(f"{draw}/ic_launcher_re_monochrome.xml", "w").write(foreground_xml(mono=True))
    for d, scale in {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}.items():
        size = round(48 * scale)
        icon = legacy(size)
        masked(icon, "square").save(f"{RES}/mipmap-{d}/ic_launcher.webp", lossless=True)
        masked(icon, "circle").save(f"{RES}/mipmap-{d}/ic_launcher_round.webp", lossless=True)

    # Preview: circle, squircle-ish rounded square, and a small 48px icon
    big = legacy(320)
    sheet = Image.new("RGBA", (320 * 2 + 48 * 2 + 60, 320), (245, 245, 245, 255))
    c = masked(big, "circle")
    sheet.paste(c, (0, 0), c)
    s = masked(big, "square")
    sheet.paste(s, (340, 0), s)
    small = masked(legacy(96), "circle")
    sheet.paste(small, (680, 112), small)
    sheet.save(PREVIEW)
